/**
 * 把 src/policy.js + src/ui.js 内联成一个 DSH 浏览器 bundle（lib/client.js）。
 *
 * DSH 的插件 bundle 是一个自包含的 CJS 工厂：执行时只注册 factory，
 * 首次被引用时才真正运行；它只能 require 平台共享模块（react 等），
 * 不能同步 require 同包的相对文件——所以这里把源码拼进同一个工厂作用域。
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** 去掉 ESM 的 import/export 语法，保留声明本身。 */
function inlineSource(relativePath) {
  const source = fs.readFileSync(path.join(root, relativePath), 'utf8')
  const stripped = source
    .replace(/^\s*import\s+[^\n]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^export\s+(?=(?:const|let|var|function|class)\b)/gm, '')
  if (/^\s*(?:import|export)\s/m.test(stripped)) {
    throw new Error(`${relativePath}: 仍有未处理的 import/export 语句`)
  }
  return stripped.trim()
}

const policy = inlineSource('src/policy.js')
const ui = inlineSource('src/ui.js')

// 动态下发的插件 bundle 必须用 window.__ModuleLoader__ 注册。
// 内置 bundle 里的 `_ModuleLoader__` 是引导脚本作用域的局部别名，第三方
// bundle 直接用它会在浏览器里抛 ReferenceError，DSH 会判定 web boot 失败
// 并回退到安全模式（禁用全部第三方 bundle）。
const bundle = `/* dsh-ds-peak-light — generated by scripts/build-client.mjs; edit src/, not this file. */
window.__ModuleLoader__.load({
	id: "dsh-ds-peak-light",
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
		const React = require("react");
		const { createElement: h, Fragment, useEffect, useState } = React;
		const primitives = require("@deepseek-ai/dsh-client-ui-primitives");
		const BrandWordmark = primitives && primitives.BrandWordmark;
		//#region src/policy.js
${indent(policy, '\t\t')}
		//#endregion
		//#region src/ui.js
${indent(ui, '\t\t')}
		//#endregion
		exports.apply = apply;
		exports.inject = inject;
		exports.PeakBrandName = PeakBrandName;
		return module.exports;
	}
});
`

function indent(text, prefix) {
  return text
    .split('\n')
    .map((line) => (line.length === 0 ? line : prefix + line))
    .join('\n')
}

const target = path.join(root, 'lib', 'client.js')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, bundle, 'utf8')
console.log(`built ${path.relative(root, target)} (${Buffer.byteLength(bundle)} bytes)`)
